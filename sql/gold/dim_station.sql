CREATE OR REPLACE TABLE GOLD.DIM_STATION AS
SELECT
    S.IDEESS        AS PK_STATION,
    S.ROTULO,
    S.MARCA,
    S.DIRECCION,
    S.MUNICIPIO,
    S.PROVINCIA,
    S.ID_CCAA,
    R.CCAA AS CCAA,
    S.LATITUD,
    S.LONGITUD
FROM SILVER.DIM_STATION AS S
LEFT JOIN SILVER.REF_CCAA AS R
       ON R.ID_CCAA = S.ID_CCAA;





