CREATE OR REPLACE TABLE GOLD.FACT_FUEL_PRICE AS
SELECT
    F.INGESTION_TS,
    CONVERT_TIMEZONE('UTC', 'Europe/Madrid', F.INGESTION_TS)::TIMESTAMP_NTZ AS INGESTION_TS_MADRID,
    HOUR(CONVERT_TIMEZONE('UTC', 'Europe/Madrid', F.INGESTION_TS))          AS HORA_MADRID,
    D.PK_DATE       AS FK_DATE,
    S.PK_STATION    AS FK_STATION,
    P.PK_PRODUCT    AS FK_PRODUCT,
    F.PRICE_EUR_L
FROM SILVER.FCT_PRICE_SNAPSHOT AS F
LEFT JOIN GOLD.DIM_DATE AS D
       ON D.PK_DATE = CONVERT_TIMEZONE('UTC', 'Europe/Madrid', F.INGESTION_TS)::DATE
LEFT JOIN GOLD.DIM_STATION AS S
       ON S.PK_STATION = F.IDEESS
LEFT JOIN GOLD.DIM_PRODUCT AS P
       ON P.PRODUCT_NAME = F.PRODUCT;



SELECT * FROM GOLD.FACT_FUEL_PRICE LIMIT 5






