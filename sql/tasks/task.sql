-- Detecta filas nuevas de la tabla RAW.
CREATE OR REPLACE STREAM CARBURANTES_DB.RAW.FUEL_STREAM
  ON TABLE CARBURANTES_DB.RAW.FUEL_PRICES_JSON
  APPEND_ONLY = TRUE;

-- Procesa la carga incremental de RAW en SILVER.
CREATE OR REPLACE TASK CARBURANTES_DB.SILVER.REFRESH_SILVER
  WAREHOUSE = SNOWFLAKE_LEARNING_WH
  WHEN SYSTEM$STREAM_HAS_DATA('CARBURANTES_DB.RAW.FUEL_STREAM')
AS
  CALL CARBURANTES_DB.SILVER.SP_REFRESH_SILVER();

-- Reconstruye o actualiza GOLD al terminar SILVER.
CREATE OR REPLACE TASK CARBURANTES_DB.GOLD.REFRESH_GOLD
  WAREHOUSE = SNOWFLAKE_LEARNING_WH
  AFTER CARBURANTES_DB.SILVER.REFRESH_SILVER
AS
  CALL CARBURANTES_DB.GOLD.SP_REFRESH_GOLD();

ALTER TASK CARBURANTES_DB.SILVER.REFRESH_SILVER RESUME;
ALTER TASK CARBURANTES_DB.GOLD.REFRESH_GOLD RESUME;

SELECT CURRENT_WAREHOUSE();